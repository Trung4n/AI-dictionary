"""Tables and figures of the report, from the saved results in reports/.

    python paper/make_assets.py                       # tables + figures from reports/ only
    python paper/make_assets.py --val-predictions <folder of val <run>.npz>   # + qualitative figure

Every number in paper/tables/*.tex and paper/figures/*.pdf comes from a file under
reports/ (named in each table's comment line). Nothing is trained and the test split
is never opened: the qualitative figure uses the saved *validation* predictions and the
local processed dataset, and is skipped when either is missing.
"""
