def hierarchy_cells(per_run: dict, runs: list[str], target: str) -> list[str]:
    cells = []
    for tree in ("semantic", "flat", "random", "shape"):
        cells.append(f"{mean(per_run[r][target][tree]['reward_area'] for r in runs):.3f}")
    gain = mean(per_run[r][target]["semantic"]["reward_area"] - per_run[r][target]["flat"]["reward_area"] for r in runs)
    prec = mean(per_run[r][target]["semantic"]["precision"] for r in runs)
    return cells + [signed(gain), f"{prec:.3f}"]


