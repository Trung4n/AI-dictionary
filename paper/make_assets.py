def figure_frontier(plt) -> None:
    """Accuracy-earliness curves of the stopping rule on validation (CNN and GRU with prefix input),
    the only runs whose full curves are kept in reports/."""
    folder = REPORTS / "anytime_v1_rescored"
    pairs = [("CNN", "cnn_prefix_s42", "cnn_anytime_s42"), ("GRU, prefix input", "gru_prefix_s42", "gru_anytime_s42")]
    fig, axes = plt.subplots(1, 2, figsize=(4.8, 2.0), sharey=True)
    for ax, (title, base, method) in zip(axes, pairs):
        b = json.loads((folder / f"{base}.json").read_text())
        m = json.loads((folder / f"{method}.json").read_text())
        for rep, policy, label, color in ((b, "pmax", "baseline, max softmax", BLUE), (m, "conf", "method, confidence head", ORANGE)):
            c = rep[policy]["curve"]
            order = np.argsort(c["earliness"])
            ax.plot(np.array(c["earliness"])[order], 100 * np.array(c["accuracy"])[order], color=color, label=label, linewidth=1.2)
            for gap, marker in (("0.02", "s"), ("0.05", "o")):
                rc = rep[policy]["risk_control"][gap]
                ax.plot(rc["earliness"], 100 * rc["accuracy"], marker=marker, color=color, markersize=4,
                        markeredgecolor="white", markeredgewidth=0.6, linestyle="none")
        ref = b["reference"]
        ax.plot(ref["oracle_first_correct"]["earliness"], 100 * ref["oracle_first_correct"]["accuracy"], marker="*",
                color=GRAY, markersize=6, linestyle="none", label="oracle (first correct)")
        ax.set_title(title)
        ax.set_xlabel("mean ink used when answering")
        ax.set_xlim(0.2, 1.0)
    axes[0].set_ylabel("accuracy (%)")
    axes[0].legend(frameon=False, loc="lower right", fontsize=6)
    save(fig, "fig_frontier")
    plt.close(fig)


