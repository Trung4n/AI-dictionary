def anytime_rows(per_run: dict) -> tuple[list[str], int, int]:
    runs = by_condition(per_run)
    lines, met, total, last = [], 0, 0, None
    for cond, policy, model, training, rule in ANYTIME_ROWS:
        rs = runs.get(cond, [])
        if not rs or policy not in rs[0]:
            continue
        if last and model != last:
            lines.append(r"\midrule")
        last = model
        cells = [model, training, rule, f"{mean(r[policy]['auc'] for r in rs):.3f}",
                 pct(mean(r["reference"]["end_of_drawing"]["accuracy"] for r in rs))]
        for gap in ("0.02", "0.05"):
            rc = [r[policy]["risk_control"][gap] for r in rs]
            met += sum(x["met"] for x in rc)
            total += len(rc)
            worst = max(x["gap"] for x in rc)
            mark = "" if all(x["met"] for x in rc) else "$^\\ast$"
            cells += [f"{100 * worst:.2f}{mark}", pct(mean(x["accuracy"] for x in rc)), f"{mean(x['earliness'] for x in rc):.3f}"]
        lines.append(" & ".join(cells) + r" \\")
    return lines, met, total


def risk_control_count(per_run: dict) -> tuple[int, int, list[str]]:
    """Targets met over every run, stopping score and gap, and the misses."""
    met, total, misses = 0, 0, []
    for run, rep in sorted(per_run.items()):
        for policy, r in rep.items():
            if policy == "reference":
                continue
            for gap, rc in r["risk_control"].items():
                total += 1
                met += bool(rc["met"])
                if not rc["met"]:
                    misses.append(f"{run} {policy} {gap}: {rc['gap']:.4f}")
    return met, total, misses


