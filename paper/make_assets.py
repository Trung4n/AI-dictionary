def load(path: str) -> dict:
    return json.loads((REPORTS / path).read_text(encoding="utf-8"))


def mean(xs) -> float:
    return float(np.mean(list(xs)))


def pct(x: float, digits: int = 1) -> str:
    return f"{100 * x:.{digits}f}"


def signed(x: float, digits: int = 3) -> str:
    return f"${'+' if x >= 0 else '-'}{abs(x):.{digits}f}$"


def write_table(name: str, source: str, body: str) -> None:
    out = PAPER / "tables" / f"{name}.tex"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(f"% Generated by paper/make_assets.py from {source}. Do not edit by hand.\n{body}", encoding="utf-8")
    print("table", out)


def by_condition(per_run: dict) -> dict:
    """{condition: [run results]} from {<condition>_s<seed>: result}."""
    out = defaultdict(list)
    for run, value in sorted(per_run.items()):
        out[run.rsplit("_s", 1)[0]].append(value)
    return out


def csv_top1(paths) -> dict:
    """{condition: {frac: mean top-1 over seeds}} from experiment results.csv files (validation)."""
    acc = defaultdict(lambda: defaultdict(list))
    for p in paths:
        with open(REPORTS / p, newline="", encoding="utf-8") as f:
            for row in csv.DictReader(f):
                if row["kind"] == "condition":
                    acc[row["condition"]][row["frac"]].append(float(row["top1"]))
    return {c: {f: mean(v) for f, v in fr.items()} for c, fr in acc.items()}


